import { test, expect } from "@playwright/test";
test("unauthenticated reviewer can reproduce cases and download exact fixture evidence", async ({ page }) => {
  const privateRequests: string[] = [];
  page.on("request", (r) => { if (/\/api\/organizations|openai|circle-fin/.test(r.url())) privateRequests.push(r.url()); });
  await page.goto("/review");
  await expect(page.getByText("SYNTHETIC DEMONSTRATION", { exact: true })).toBeVisible();
  const decision = page.locator(".review-decision");
  await expect(decision.getByRole("heading", { level: 3 })).toHaveText("ASK");
  await page.getByRole("button", { name: "Add synthetic owner acceptance" }).click();
  await expect(decision.getByRole("heading", { level: 3 })).toHaveText("PAY");
  await page.getByRole("button", { name: /02 Corrections/ }).click();
  await expect(decision.getByRole("heading", { level: 3 })).toHaveText("ASK");
  await page.getByRole("button", { name: "Accept synthetic version 2" }).click();
  await expect(decision.getByRole("heading", { level: 3 })).toHaveText("PAY");
  await page.getByRole("button", { name: /03 Pay the remainder/ }).click();
  await page.getByRole("button", { name: "Record synthetic first half" }).click();
  await expect(page.locator(".review-flow")).toContainText("400 USDC");
  await page.getByRole("button", { name: /04 Renaming/ }).click();
  await page.getByRole("button", { name: "Rename the synthetic invoice" }).click();
  await expect(decision.getByRole("heading", { level: 3 })).toHaveText("HOLD");
  await page.getByRole("button", { name: /05 A timeout/ }).click();
  await page.getByRole("button", { name: "Run synthetic timeout" }).click();
  await expect(page.getByLabel("Execution reducer result")).toContainText("Repeat submission rejected");
  await page.getByRole("button", { name: /Inspect exact/ }).click();
  await expect(page.locator(".review-source")).toContainText("verifyObligation");
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download fixture trace" }).click();
  expect((await downloadEvent).suggestedFilename()).toBe("countersign-synthetic-uncertain.json");
  expect(privateRequests).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
});
