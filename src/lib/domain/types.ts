/** Decimal strings represent nonnegative atomic units; never JavaScript floating-point money. */
export type Atomic = string;
export type Mode = "observe" | "prepare" | "delegate";
export type Action = "PAY" | "SCHEDULE" | "HOLD" | "ASK" | "PROPOSE_PARTIAL";
export type SourceRef = Readonly<{
  id: string;
  uri: string;
  location: string;
  hash: string;
  observedAt: string;
}>;
export type Asset = Readonly<{
  symbol: string;
  chainId: number;
  address: string;
  decimals: number;
}>;
export type Destination = Readonly<{
  chainId: number;
  address: string;
  version: number;
  verifiedBy: string;
  verifiedAt: string;
}>;
export type Engagement = Readonly<{
  id: string;
  tenantId: string;
  vendorId: string;
  version: number;
  approvedBy: string;
  approvedAt: string;
  status: "draft" | "active" | "revoked";
  mode: Mode;
  effectiveFrom: string;
  effectiveUntil: string;
  billingModel: "retainer" | "hourly" | "milestone";
  currency: string;
  amount: Atomic;
  hourlyRate?: Atomic;
  maximumQuantity?: string;
  commitmentCeiling: Atomic;
  partialPayments: boolean;
  minimumPartial?: Atomic;
  authorizedAcceptors: readonly string[];
  acceptanceRequired: boolean;
  acceptanceMaxAgeSeconds: number;
  destinations: readonly Destination[];
  asset: Asset;
  source: SourceRef;
}>;
export type Invoice = Readonly<{
  id: string;
  tenantId: string;
  vendorId: string;
  engagementId: string;
  engagementVersion: number;
  version: number;
  obligationId: string;
  reference: string;
  periodStart: string;
  periodEnd: string;
  dueAt: string;
  amount: Atomic;
  currency: string;
  destination: Destination;
  description: string;
  source: SourceRef;
  quantity?: string;
  status: "received" | "matched" | "disputed" | "canceled";
}>;
export type Acceptance = Readonly<{
  id: string;
  tenantId: string;
  engagementId: string;
  engagementVersion: number;
  obligationId: string;
  actorId: string;
  acceptedAt: string;
  expiresAt: string;
  kind: "acceptance" | "activity";
  source: SourceRef;
  revoked: boolean;
}>;
export type Allocation = Readonly<{
  id: string;
  tenantId: string;
  engagementId: string;
  obligationId: string;
  invoiceId: string;
  paymentId: string;
  amount: Atomic;
  state: "reserved" | "submitted" | "settled" | "released";
}>;
export type Policy = Readonly<{
  id: string;
  tenantId: string;
  version: number;
  paused: boolean;
  perPaymentCap: Atomic;
  remainingDelegation: Atomic;
  rolling24hRemaining: Atomic;
  expiresAt: string;
  coverageRequired: boolean;
}>;
export type Finding = Readonly<{
  code: string;
  severity: "hold" | "ask" | "info";
  message: string;
  sourceIds: readonly string[];
}>;
export type Decision = Readonly<{
  schemaVersion: 1;
  tenantId: string;
  invoiceId: string;
  invoiceVersion: number;
  engagementId: string;
  engagementVersion: number;
  policyVersion: number;
  action: Action;
  executable: boolean;
  amount: Atomic;
  reason: string;
  findings: readonly Finding[];
  evaluatedAt: string;
  validUntil: string;
  nextCheck: string;
  sourceIds: readonly string[];
  availableActions: readonly Action[];
}>;
export type VerificationInput = Readonly<{
  tenantId: string;
  now: string;
  engagement: Engagement;
  invoice: Invoice;
  policy: Policy;
  expectedPolicyVersion: number;
  acceptances: readonly Acceptance[];
  allocations: readonly Allocation[];
  historySyncedAt: string;
  historyMaxAgeSeconds: number;
  unmatchedExternalTransfers: boolean;
  requestedAmount?: Atomic;
  coverageReserved?: boolean;
}>;
